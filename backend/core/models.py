import uuid
from django.db import models
from django.utils import timezone


class PartnerShop(models.Model):
    """
    Rental and technical partner shop providing bikes, gear, and local support.
    """
    id = models.UUIDField(primary_key=True, default=uuid.uuid4, editable=False)
    name = models.CharField(max_length=200, help_text="Nome del partner o negozio di noleggio")
    address = models.CharField(max_length=300, help_text="Indirizzo fisico completo")
    latitude = models.FloatField(help_text="Latitudine WGS84")
    longitude = models.FloatField(help_text="Longitudine WGS84")
    total_bikes = models.PositiveIntegerField(default=10, help_text="Numero totale di bici in flotta")
    available_bikes = models.PositiveIntegerField(default=10, help_text="Bici attualmente disponibili per noleggio")
    contact_phone = models.CharField(max_length=50, blank=True, help_text="Telefono o WhatsApp")
    contact_email = models.EmailField(blank=True, help_text="Email per notifiche di prenotazione")
    is_active = models.BooleanField(default=True, help_text="Partner attivo e operativo")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "Partner Shop"
        verbose_name_plural = "Partner Shops"
        ordering = ['name']

    def __str__(self):
        return f"{self.name} ({self.available_bikes}/{self.total_bikes} bici disponibili)"

    @property
    def has_availability(self) -> bool:
        return self.is_active and self.available_bikes > 0


class Tour(models.Model):
    """
    Curated cycling or outdoor trail loaded with GPX track and enriched POIs.
    """
    id = models.BigAutoField(primary_key=True)
    title = models.CharField(max_length=255, help_text="Titolo del tour")
    description = models.TextField(blank=True, help_text="Descrizione del percorso e consigli tecnici")
    gpx_file = models.FileField(upload_to='gpx_tracks/', blank=True, null=True, help_text="File GPX del percorso")
    distance_km = models.FloatField(default=0.0, help_text="Distanza totale calcolata in km")
    elevation_gain_m = models.FloatField(default=0.0, help_text="Dislivello positivo totale (D+) in metri")
    estimated_duration_min = models.PositiveIntegerField(default=0, help_text="Durata stimata in minuti")
    
    # Waypoints / POIs stored as JSON
    # Format: [
    #   {
    #     "id": 1,
    #     "name": "Point Name",
    #     "latitude": 45.98,
    #     "longitude": 9.26,
    #     "elevation": 215,
    #     "notes": "Original tourist notes",
    #     "ai_guide": "Audio-ready script generated by AI",
    #     "category": "VIEWPOINT | MONUMENT | CAFE | BIKE_STOP"
    #   }
    # ]
    waypoints = models.JSONField(default=list, blank=True, help_text="Lista waypoints e punti di interesse (POI) in formato JSON")
    
    # Coordinates polyline for fast map rendering: [{"latitude": 45.98, "longitude": 9.26}, ...]
    polyline = models.JSONField(default=list, blank=True, help_text="Coordinate della traccia pronte per il render su mappa")
    
    is_published = models.BooleanField(default=True, help_text="Visibile agli utenti")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "Tour"
        verbose_name_plural = "Tours"
        ordering = ['-created_at']

    def __str__(self):
        return f"{self.title} ({self.distance_km:.1f} km, +{self.elevation_gain_m:.0f}m)"

    @property
    def start_point(self):
        """Returns the first coordinate (lat, lng) of the tour."""
        if self.polyline and len(self.polyline) > 0:
            first = self.polyline[0]
            return first.get('latitude'), first.get('longitude')
        if self.waypoints and len(self.waypoints) > 0:
            first = self.waypoints[0]
            return first.get('latitude'), first.get('longitude')
        return None, None


class Booking(models.Model):
    """
    Rider booking redeemable via code (e.g. OUT-1234).
    """
    STATUS_CONFIRMED = 'CONFIRMED'
    STATUS_IN_PROGRESS = 'IN_PROGRESS'
    STATUS_COMPLETED = 'COMPLETED'
    STATUS_CANCELLED = 'CANCELLED'

    STATUS_CHOICES = [
        (STATUS_CONFIRMED, 'Confermata (Non avviata)'),
        (STATUS_IN_PROGRESS, 'In Corso'),
        (STATUS_COMPLETED, 'Completata'),
        (STATUS_CANCELLED, 'Annullata'),
    ]

    id = models.BigAutoField(primary_key=True)
    booking_code = models.CharField(
        max_length=30,
        unique=True,
        db_index=True,
        help_text="Codice univoco prenotazione (es. OUT-1234)"
    )
    customer_name = models.CharField(max_length=150, help_text="Nome e cognome del ciclista")
    customer_email = models.EmailField(help_text="Email per comunicazioni e recap")
    tour_date = models.DateTimeField(default=timezone.now, help_text="Data e ora prevista per il tour")
    
    partner_shop = models.ForeignKey(
        PartnerShop,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name='bookings',
        help_text="Negozio partner assegnato per ritiro e assistenza bici"
    )
    
    tour = models.ForeignKey(
        Tour,
        on_delete=models.CASCADE,
        related_name='bookings',
        help_text="Tour associato alla prenotazione"
    )
    
    status = models.CharField(
        max_length=20,
        choices=STATUS_CHOICES,
        default=STATUS_CONFIRMED,
        db_index=True,
        help_text="Stato attuale della corsa"
    )
    
    activated_at = models.DateTimeField(null=True, blank=True, help_text="Timestamp di sblocco/attivazione da mobile")
    completed_at = models.DateTimeField(null=True, blank=True, help_text="Timestamp di completamento corsa")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        verbose_name = "Prenotazione (Booking)"
        verbose_name_plural = "Prenotazioni (Bookings)"
        ordering = ['-tour_date']

    def __str__(self):
        return f"[{self.booking_code}] {self.customer_name} - {self.tour.title} ({self.status})"

    def activate(self):
        """Activates the booking when cyclist starts the ride."""
        self.status = self.STATUS_IN_PROGRESS
        if not self.activated_at:
            self.activated_at = timezone.now()
        self.save(update_fields=['status', 'activated_at', 'updated_at'])

    def complete(self):
        """Marks ride as completed."""
        self.status = self.STATUS_COMPLETED
        self.completed_at = timezone.now()
        self.save(update_fields=['status', 'completed_at', 'updated_at'])
